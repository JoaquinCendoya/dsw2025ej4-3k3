    private void agregarAnimalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarAnimalActionPerformed
    int s;
    double val;
    try {
        s = Integer.parseInt((String)sectorBox.getSelectedItem());
        val= Double.parseDouble(valorFijoText.getText().trim());
        Controlador.agregarAnimalNuevo(nombreText,origenText,pesoText,alimenBox,s,extraText,edadText,codIso,val);   
        } catch (NumberFormatException e) {
        throw new IllegalArgumentException("El número de sector debe ser un valor entero.");
    }
    }//GEN-LAST:event_agregarAnimalActionPerformed

