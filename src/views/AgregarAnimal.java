    private void alimenBoxItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_alimenBoxItemStateChanged
         if (evt.getStateChange() == ItemEvent.SELECTED) {
                    String seleccionado = (String) evt.getItem();
                    if ("Herbivoro".equals(seleccionado)) {
                        herbivoroPanel.setVisible(true);
                        cambiarSectores(data.Persistencia.getSectoresHerbivoro());
                    }
                    if("Carnivoro".equals(seleccionado)){
                        herbivoroPanel.setVisible(false);
                        cambiarSectores(data.Persistencia.getSectoresCarnivoro());
                    }
        }
    }//GEN-LAST:event_alimenBoxItemStateChanged

